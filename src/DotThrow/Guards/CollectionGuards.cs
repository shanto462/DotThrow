namespace DotThrow;

// Collection checks. A null collection fails with the "Null" code.
//
// The count checks have overloads for the common shapes (arrays, List, HashSet, Dictionary,
// ICollection, IList, IReadOnlyCollection, IReadOnlyList, IEnumerable of T), which read
// Count or Length directly, and a fallback for any IEnumerable that never enumerates a
// collection with a Count and stops enumerating as soon as the answer is known. The C#
// compiler picks the most specific overload, so a List<T> never pays for interface checks.
//
// The count checks follow one pattern for every shape; they were generated by a script
// (verify/tools/gen_collections.py in the core-guards working copy). Keep every shape in
// sync when you change one.
public static partial class GuardExtensions
{
    /// <summary>Fails when the collection is <see langword="null"/> or has no items.</summary>
    /// <typeparam name="TCollection">The collection type.</typeparam>
    /// <param name="guard">The guard.</param>
    /// <param name="message">A custom message, or <see langword="null"/> for the default one.</param>
    /// <returns>The guard.</returns>
    public static Guard<TCollection> IfNullOrEmpty<TCollection>(this Guard<TCollection> guard, string? message = null)
        where TCollection : IEnumerable
    {
        var value = guard.Value;
        if (guard.IsActive && (value is null || Collections.CountUpTo(value, 1) == 0))
        {
            return Rejection.Content(guard, FailureKind.Argument, ErrorCodes.Empty, message);
        }

        return guard;
    }

