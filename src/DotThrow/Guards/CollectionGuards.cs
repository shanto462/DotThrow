    /// <summary>Fails when the collection has exactly <paramref name="count"/> items.</summary>
    /// <typeparam name="TCollection">The collection type.</typeparam>
    /// <param name="guard">The guard.</param>
    /// <param name="count">The rejected number of items.</param>
    /// <param name="message">A custom message, or <see langword="null"/> for the default one. Placeholder: <c>{Count}</c>.</param>
    /// <returns>The guard.</returns>
    public static Guard<TCollection> IfCountEqualTo<TCollection>(this Guard<TCollection> guard, int count, string? message = null)
        where TCollection : IEnumerable
    {
        Argument.NotNegative(count);
        var value = guard.Value;
        if (guard.IsActive && (value is null || Collections.CountUpTo(value, Above(count)) == count))
        {
            return Rejection.Content(guard, FailureKind.Argument, ErrorCodes.CountEqualTo, message, Placeholder.Count, count, count == 1 ? TemplateKeys.CountEqualToOne : null);
        }

        return guard;
    }

